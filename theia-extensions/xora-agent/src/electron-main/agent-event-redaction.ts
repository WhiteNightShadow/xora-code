import {
    AgentHostEvent,
    AgentSessionContext,
    AgentToolPresentation,
    RuntimeSnapshot,
    SessionRecord
} from '../common/agent-protocol';
import { deepRedact } from './session-repository';

/**
 * Redact a host-constructed event without rewriting its control plane.
 *
 * An exact credential can be as short as "1" or "-". Applying substring
 * replacement to the whole event changes UUIDs, discriminants and filesystem
 * roots, so the renderer cannot address the session and persistence may drop
 * the event entirely. Only the explicit host protocol paths below are exempt.
 * Never pass a raw ACP response here: arbitrary payloads (including objects
 * with names such as sessionId, kind or model) must still use deepRedact.
 *
 * Opaque provider-authored correlation ids and descriptive text remain subject
 * to redaction. The exemptions are local routing/selection state or finite
 * protocol enums, never tool input/output, labels, URLs, errors or chat text.
 */
export function redactAgentHostEvent<T extends AgentHostEvent>(event: T, exactSecrets?: readonly string[]): T;
export function redactAgentHostEvent(event: AgentHostEvent, exactSecrets: readonly string[] = []): AgentHostEvent {
    const safe = deepRedact(event, exactSecrets);
    switch (event.kind) {
        case 'snapshot': {
            const target = safe as Extract<AgentHostEvent, { kind: 'snapshot' }>;
            target.kind = 'snapshot';
            restoreSnapshot(target.snapshot, event.snapshot);
            return safe;
        }
        case 'session': {
            const target = safe as Extract<AgentHostEvent, { kind: 'session' }>;
            target.kind = 'session';
            restoreSession(target.session, event.session);
            return safe;
        }
        case 'session-deleted':
        case 'text-delta':
        case 'thought-delta':
        case 'plan':
        case 'plan-approval-request':
        case 'goal-state':
        case 'task-contract':
        case 'supervision-shadow':
        case 'tool-call':
        case 'permission-request':
        case 'diff':
        case 'context-usage':
        case 'turn-completed':
        case 'error':
            // This is an exact discriminated-union boundary, not a recursive
            // field-name exemption. Nested payloads retain their redaction.
            safe.kind = event.kind;
            restore(safe, event, ['sessionId', 'turnId']);
            break;
        default:
            return safe;
    }
    switch (event.kind) {
        case 'text-delta':
            restoreEnum(safe, event, 'role', ['assistant', 'user', 'system']);
            if (event.attachments) {
                const target = safe as typeof event;
                for (let index = 0; index < event.attachments.length; index++) {
                    const attachment = event.attachments[index];
                    const redacted = target.attachments![index];
                    restoreEnum(redacted, attachment, 'kind', ['image']);
                    restoreEnum(redacted, attachment, 'mimeType', ['image/png', 'image/jpeg', 'image/webp']);
                    // These are generated by Xora after attachment admission;
                    // the display name and all unexpected fields stay redacted.
                    restore(redacted, attachment, ['sha256', 'workspacePath']);
                }
            }
            break;
        case 'thought-delta':
            restore(safe, event, ['startedAt']);
            break;
        case 'plan': {
            restore(safe, event, ['providerRuntimeEpoch']);
            restoreEnum(safe, event, 'outcome', ['completed', 'cancelled', 'failed']);
            const target = safe as typeof event;
            event.entries.forEach((entry, index) => restoreEnum(target.entries[index], entry, 'status',
                ['pending', 'in-progress', 'completed', 'failed', 'cancelled']));
            break;
        }
        case 'goal-state':
            restore(safe, event, ['providerRuntimeEpoch']);
            restoreEnum(safe, event, 'status', ['active', 'user-paused', 'back-off-paused', 'no-progress-paused',
                'infra-paused', 'blocked', 'budget-limited', 'complete', 'cleared', 'unknown']);
            restoreEnum(safe, event, 'phase', ['idle', 'planning', 'executing', 'unknown']);
            restoreEnum(safe, event, 'agentTurnStatus', ['running', 'end-turn', 'cancelled', 'error']);
            restoreEnum(safe, event, 'verificationStatus', ['not-required', 'working', 'verifying', 'verified',
                'incomplete', 'blocked', 'paused']);
            restoreEnum(safe, event, 'classifierVerdict', ['achieved', 'not-achieved', 'inconclusive', 'unknown']);
            if (typeof event.tokenBudget === 'number' && Number.isSafeInteger(event.tokenBudget) && event.tokenBudget >= 0) {
                (safe as typeof event).tokenBudget = event.tokenBudget;
            }
            break;
        case 'task-contract':
            restore(safe, event, ['providerRuntimeEpoch', 'approvedAt', 'updatedAt']);
            restoreEnum(safe, event, 'lifecycle', ['approved', 'goal-starting', 'goal-active', 'verified', 'interrupted']);
            break;
        case 'plan-approval-request':
            restore(safe, event, ['requestId', 'requestedAt']);
            break;
        case 'supervision-shadow': {
            const target = safe as typeof event;
            event.reasons.forEach((reason, index) => {
                if (['open-plan', 'tool-failure', 'missing-test-evidence'].includes(reason)) target.reasons[index] = reason;
            });
            break;
        }
        case 'tool-call':
            restore(safe, event, ['startedAt']);
            restoreEnum(safe, event, 'status', ['pending', 'running', 'completed', 'failed', 'rejected']);
            restorePresentation((safe as typeof event).presentation, event.presentation);
            break;
        case 'permission-request': {
            restore(safe, event, ['requestId']);
            restorePresentation((safe as typeof event).presentation, event.presentation);
            const target = safe as typeof event;
            event.options.forEach((option, index) => {
                if (['allow-once', 'allow-always', 'reject'].includes(option)) target.options[index] = option;
            });
            break;
        }
        case 'diff':
            restore(safe, event, ['diffId', 'oldHash', 'newHash']);
            break;
        case 'context-usage':
            restoreContext((safe as typeof event).context, event.context);
            break;
        case 'error':
            restore(safe, event, ['errorGroupId']);
            break;
    }
    return safe;
}

/** Explicit leaf paths only; callers decide which host-owned values are safe. */
function restore(target: object, source: object, keys: readonly string[]): void {
    const original = source as Record<string, unknown>;
    const redacted = target as Record<string, unknown>;
    for (const key of keys) {
        if (typeof original[key] === 'string') redacted[key] = original[key];
    }
}

function restoreEnum(target: object, source: object, key: string, values: readonly string[]): void {
    const value = (source as Record<string, unknown>)[key];
    if (typeof value === 'string' && values.includes(value)) (target as Record<string, unknown>)[key] = value;
}

function restoreSession(target: SessionRecord, source: SessionRecord): void {
    // These values have already been admitted by the host/repository/provider
    // registry and are used as RPC addresses or exact selection values. A
    // session title and unknown metadata are not part of this projection.
    restore(target, source, ['appSessionId', 'providerId', 'providerRuntimeEpoch', 'workspaceRoot',
        'model', 'reasoningEffort', 'currentModeId', 'createdAt', 'updatedAt', 'sidecarVersion']);
    restoreEnum(target, source, 'status', ['idle', 'running', 'completed', 'cancelled', 'failed', 'read-only']);
    source.availableModes?.forEach((mode, index) => restore(target.availableModes![index], mode, ['id']));
}

function restoreSnapshot(target: RuntimeSnapshot, source: RuntimeSnapshot): void {
    restore(target, source, ['workspaceRoot', 'providerId', 'activeSessionId', 'selectedModel',
        'selectedReasoningEffort', 'preferredReasoningEffort', 'sidecarVersion']);
    restoreEnum(target, source, 'phase', ['stopped', 'starting', 'initializing', 'auth-required', 'ready', 'draining', 'updating', 'crashed']);
    restoreEnum(target, source, 'permissionMode', ['request-approval', 'full-access']);
    restoreEnum(target, source, 'grokSubscriptionAuthStatus', ['authenticated', 'unauthenticated', 'unknown']);
    source.sessions?.forEach((session, index) => restoreSession(target.sessions[index], session));
    source.models?.forEach((model, index) => {
        const redacted = target.models[index];
        restore(redacted, model, ['id']);
        model.reasoningOptions?.forEach((option, optionIndex) =>
            restore(redacted.reasoningOptions![optionIndex], option, ['id', 'value']));
    });
    if (source.capabilities && target.capabilities) {
        restore(target.capabilities, source.capabilities, ['defaultAuthMethodId']);
        source.capabilities.authMethods?.forEach((method, index) => restore(target.capabilities!.authMethods[index], method, ['id']));
    }
    for (const [sessionId, context] of Object.entries(source.sessionContexts ?? {})) {
        const redacted = target.sessionContexts?.[sessionId];
        if (redacted) restoreContext(redacted, context);
    }
}

function restoreContext(target: AgentSessionContext, source: AgentSessionContext): void {
    restore(target, source, ['modelId']);
    restoreEnum(target, source, 'compactionStatus', ['idle', 'running', 'failed', 'cancelled']);
}

function restorePresentation(target: AgentToolPresentation | undefined, source: AgentToolPresentation | undefined): void {
    if (!target || !source) return;
    restoreEnum(target, source, 'action', ['file-read', 'file-create', 'file-write', 'file-delete', 'file-move',
        'project-search', 'web-search', 'web-fetch', 'terminal', 'test', 'browser', 'plan', 'subagent', 'other']);
    restoreEnum(target, source, 'source', ['builtin', 'skill', 'mcp', 'plugin']);
}
